"""Write the evaluation as JSON, CSV and a readable Markdown report."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from fraudnet.evaluate.comparisons import COMPARISONS, PRINCIPLES
from fraudnet.evaluate.run import HEADLINE

LABELS = {"precision": "Precision", "recall": "Ring recall", "fraud_group_recall": "Fraud group recall (rings + EC-3)",
          "false_positive_rate": "Look-alike false-positive rate", "false_negative_rate": "False-negative rate",
          "average_precision": "Average precision", "r_precision": "R-precision (top N, N = fraud groups)",
          "ndcg_at_r": "NDCG at N", "precision_at_10": "Precision@10",
          "mean_match_jaccard": "Mean match Jaccard"}


def _fmt(value) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _spread(item: dict) -> str:
    if item["mean"] is None:
        return "n/a"
    return f"{item['mean']:.3f} ± {item['std']:.3f}" if item["std"] else f"{item['mean']:.3f}"


def markdown(development: dict, unseen: dict | None, command: str) -> str:
    detector = development["detector"]
    lines = [
        "# Evaluation report",
        "",
        f"Generated by `{command}`. The detector never reads labels. Only this evaluation compares its output with",
        "`hidden/ground_truth.csv`. Thresholds were tuned on the development seed only.",
        "",
        "## Headline results",
        "",
        f"| Measure | Development seed {development['seed']} |" +
        (f" Unseen seeds {', '.join(map(str, unseen['seeds']))} (mean ± sd) |" if unseen else ""),
        "|---|---:|" + ("---:|" if unseen else ""),
    ]
    for metric in HEADLINE:
        row = f"| {LABELS[metric]} | {_fmt(detector.get(metric))} |"
        if unseen:
            row += f" {_spread(unseen['detector'][metric])} |"
        lines.append(row)
    top = detector["fraud_groups_in_top_n"]
    lines += ["", f"Flagged networks: {detector['flagged_networks']}, of which {detector['true_positive_networks']} "
                  f"match a fraud group and {detector['false_positive_networks']} don't. Fraud groups (rings and EC-3) in the "
                  f"top {top['n']} networks: {top['found']} of {top['n']}.", ""]

    lines += ["## Per rule (development seed)", "", "| Rule | Groups | Flagged | Recall or false-positive rate |",
              "|---|---:|---:|---:|"]
    for rule, item in detector["per_rule"].items():
        if rule == "B-PROV-01":
            lines.append(f"| {rule} (popular providers) | {item['popular_providers']} | {item['in_flagged_networks']} | "
                         f"FP rate {_fmt(item['false_positive_rate'])} |")
            continue
        key = "recall" if "recall" in item else "false_positive_rate"
        lines.append(f"| {rule} | {item['groups']} | {item['flagged']} | "
                     f"{'recall' if key == 'recall' else 'FP rate'} {_fmt(item[key])} |")

    lines += ["", "## Edge cases (development seed)", "", "| ID | Check | Result | Status |", "|---|---|---|---|"]
    for case, item in development["edge_cases"].items():
        facts = ", ".join(f"{key.replace('_', ' ')} {value}" for key, value in item.items() if key not in {"rule", "status"})
        lines.append(f"| {case} | {item['rule']} | {facts} | {item['status']} |")
    lines += ["", "**Exceptions reconciled with labels in both directions:** " +
              ", ".join(f"{kind} {item['status']}" for kind, item in development["exceptions"].items()) + ".",
              f"**Explanation check:** {development['explanations']['ids_cited']} cited IDs, all found in the input: "
              f"{development['explanations']['status']}.", ""]

    if "comparisons" in development:
        lines += ["## What each design choice adds", "",
                  "| Method | Precision | Ring recall | Look-alike FP rate | Flagged networks |", "|---|---:|---:|---:|---:|",
                  f"| **Full detector** | {_fmt(detector['precision'])} | {_fmt(detector['recall'])} | "
                  f"{_fmt(detector['false_positive_rate'])} | {detector['flagged_networks']} |"]
        for name, description in {**COMPARISONS, **PRINCIPLES}.items():
            item = development["comparisons"].get(name) or development["principles_off"][name]
            lines.append(f"| {description} | {_fmt(item['precision'])} | {_fmt(item['recall'])} | "
                         f"{_fmt(item['false_positive_rate'])} | {item['flagged_networks']} |")
        lines.append("")
    if unseen and "comparisons" in unseen:
        lines += ["Across the unseen seeds (mean ± sd):", "",
                  "| Method | Precision | Ring recall | Look-alike FP rate |", "|---|---:|---:|---:|",
                  f"| **Full detector** | {_spread(unseen['detector']['precision'])} | "
                  f"{_spread(unseen['detector']['recall'])} | {_spread(unseen['detector']['false_positive_rate'])} |"]
        for section in ("comparisons", "principles_off"):
            for name, item in unseen[section].items():
                description = {**COMPARISONS, **PRINCIPLES}[name]
                lines.append(f"| {description} | {_spread(item['precision'])} | {_spread(item['recall'])} | "
                             f"{_spread(item['false_positive_rate'])} |")
        lines.append("")
    if unseen:
        lines += ["## Checks on every unseen seed", ""]
        lines += [f"- {name}: {'PASS' if passed else 'FAIL'}" for name, passed in unseen["checks_passed"].items()]
        lines.append("")
    lines += ["## Limits of this evaluation", "",
              "- Every seed comes from the same generator, so this measures stability across data drawn the same way,",
              "  not performance on real claims.",
              "- Labels follow documented planting rules, and the detector was designed knowing those patterns exist.",
              "  Perfect scores mean these documented patterns are separated cleanly, not that real fraud would be.",
              "- Seeds 777 and 4242 (D-028) and 101-505 (D-029) were looked at while fixing the detector, so they are",
              "  not used as unseen seeds.", ""]
    return "\n".join(lines)


def write_report(folder: Path, development: dict, unseen_results: list[dict] | None, unseen: dict | None,
                 command: str, doc: Path | None = None) -> None:
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    body = {"development": development, "unseen_seeds": unseen, "unseen_results": unseen_results or []}
    (folder / "evaluation_report.json").write_bytes((json.dumps(body, indent=2, sort_keys=True) + "\n").encode("utf-8"))
    matches = pd.DataFrame(development["detector"]["matches"])
    (folder / "network_matches.csv").write_bytes(matches.to_csv(index=False, lineterminator="\n").encode("utf-8"))
    text = markdown(development, unseen, command)
    (folder / "evaluation_report.md").write_bytes(text.encode("utf-8"))
    if doc:
        Path(doc).write_bytes(text.encode("utf-8"))
