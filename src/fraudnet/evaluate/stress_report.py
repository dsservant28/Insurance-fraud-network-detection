"""Markdown report for the stress evaluation: docs/STRESS.md."""
from __future__ import annotations

from collections import Counter
from pathlib import Path

from fraudnet.evaluate.stress import RING_RULES, TITLES, hypotheses_verdicts

EXAMPLES = 2


def _f(value, digits: int = 3) -> str:
    if value is None:
        return "–"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _mean_of(values):
    present = [value for value in values if value is not None]
    return round(sum(present) / len(present), 4) if present else None


def _name(condition: str) -> str:
    if condition == "baseline":
        return "Baseline (no stress)"
    name, level = condition.split("@", 1)
    return f"{name} {TITLES[name]}: {level}"


def _actual(item: dict) -> str:
    return "; ".join(f"{level}: {_f(value) if not isinstance(value, (list, str)) else value}"
                     for level, value in item["actual"].items())


def markdown(result: dict, command: str) -> str:
    table, predictions = result["table"], result["predictions"]
    hits = sum(item["hit"] for item in predictions)
    lines = [
        "# Stress test results",
        "",
        f"Generated by `{command}`. The plan, scenarios and every prediction below were registered in",
        "[STRESS_PLAN.md](STRESS_PLAN.md) and pushed before any stress data or stress code existed.",
        "",
        f"- Detector under test: frozen at commit `{result['frozen_commit'][:12]}`, settings SHA-256 "
        f"`{result['config_sha256'][:12]}`.",
        f"- Stress seeds: {', '.join(map(str, result['seeds']))}, at scale 1.0. Every figure is the mean over these seeds.",
        "- A prediction is a hit only when the mean lies inside its registered range.",
        "",
        "## Summary",
        "",
        f"**Predictions hit: {hits} of {len(predictions)}.**",
        "",
        "| Hypothesis | Predictions hit |",
        "|---|---:|",
    ]
    for key, verdict in hypotheses_verdicts(predictions).items():
        lines.append(f"| {key}: {verdict['text']} | {verdict['hits']} of {verdict['predictions']} |")

    lines += ["", "## Results by scenario", "",
              "| Scenario and level | Precision | Ring recall | Worst innocent FP rate | Flagged networks | Mean match Jaccard |",
              "|---|---:|---:|---:|---:|---:|"]
    for condition, row in table.items():
        lines.append(f"| {_name(condition)} | {_f(row['precision']['mean'])} | {_f(row['recall']['mean'])} | "
                     f"{_f(row['max_benign_fp']['mean'])} | {_f(row['flagged_networks']['mean'], 1)} | "
                     f"{_f(row['mean_match_jaccard']['mean'])} |")

    lines += ["", "## Recall per ring rule", "", "| Scenario and level | " + " | ".join(RING_RULES) + " | EC-3 |",
              "|---|" + "---:|" * (len(RING_RULES) + 1)]
    for condition, row in table.items():
        cells = [_f(row["per_rule"].get(rule)) for rule in (*RING_RULES, "EC-3")]
        lines.append(f"| {_name(condition)} | " + " | ".join(cells) + " |")

    benign = sorted({rule for row in table.values() for rule, value in row["per_rule"].items()
                     if rule.startswith("B-") and value})
    if benign:
        lines += ["", "## False-positive rate per innocent rule (rules with any false alarm)", "",
                  "| Scenario and level | " + " | ".join(benign) + " |", "|---|" + "---:|" * len(benign)]
        for condition, row in table.items():
            if any(row["per_rule"].get(rule) for rule in benign):
                lines.append(f"| {_name(condition)} | " + " | ".join(_f(row["per_rule"].get(rule)) for rule in benign) + " |")

    lines += ["", "## Predictions against results", "",
              "| ID | Hypothesis | Condition | Predicted | Actual (mean) | Result |", "|---|---|---|---|---|---|"]
    for item in predictions:
        condition = item["condition"] + (f" @ {', '.join(item['levels'])}" if item["levels"] else "")
        lines.append(f"| {item['pid']} | {item['hypothesis']} | {condition} | {item['predicted']} | "
                     f"{_actual(item)} | {'HIT' if item['hit'] else '**MISS**'} |")

    development = result["development"]
    baseline_runs = result["by_condition"].get("baseline", [])
    lines += ["", "## Flag threshold sweep", "",
              "Precision and ring recall if the flag threshold were changed, for the networks the detector formed. "
              "Stress seeds are shown with no stress applied (mean).", "",
              "| Threshold | Dev seed: flagged | Dev seed: precision | Dev seed: recall | Stress seeds: precision | "
              "Stress seeds: recall |", "|---:|---:|---:|---:|---:|---:|"]
    for position, row in enumerate(development["sweep"]):
        mark = " (current)" if row["threshold"] == 0.6 else ""
        stress = [run["sweep"][position] for run in baseline_runs]
        precision = _mean_of([item["precision"] for item in stress])
        recall = _mean_of([item["recall"] for item in stress])
        lines.append(f"| {row['threshold']:.2f}{mark} | {row['flagged']} | {_f(row['precision'])} | {_f(row['recall'])} | "
                     f"{_f(precision)} | {_f(recall)} |")

    sensitivity = result["sensitivity"]
    if sensitivity["rows"]:
        moved = [row for row in sensitivity["rows"]
                 if abs((row["precision"] or 0) - (development["precision"] or 0)) > 0.05
                 or abs((row["recall"] or 0) - (development["recall"] or 0)) > 0.05]
        lines += ["", "## Setting sensitivity (development seed, each setting moved 30% down and up)", "",
                  f"{len(sensitivity['rows']) // 2} settings tested. {len(sensitivity['sensitive'])} change precision or "
                  "recall by more than 0.05:", "",
                  "| Setting | From | To | Precision | Ring recall |", "|---|---:|---:|---:|---:|"]
        for row in moved:
            lines.append(f"| {row['setting']} | {_f(row['from'])} | {_f(row['to'])} | {_f(row['precision'])} | "
                         f"{_f(row['recall'])} |")

    lines += ["", "## Investigator capacity", "",
              "Fraud groups (rings and EC-3) among the top-ranked networks, mean over seeds.", "",
              "| Scenario and level | Fraud groups | In top 10 | In top 20 | In top 50 |", "|---|---:|---:|---:|---:|"]
    for condition, row in table.items():
        capacity = row["capacity"]
        lines.append(f"| {_name(condition)} | {_f(row['fraud_groups'], 1)} | {_f(capacity['10'], 1)} | "
                     f"{_f(capacity['20'], 1)} | {_f(capacity['50'], 1)} |")

    lines += ["", "## Failure gallery", "",
              "Why rings were missed and what the false alarms were, counted over all stress seeds, with examples "
              "from the first seed that shows each failure. The evidence is the detector's own output.", ""]
    for condition, runs in result["by_condition"].items():
        misses = [(run["seed"], miss) for run in runs for miss in run["gallery"]["missed_rings"]]
        alarms = [(run["seed"], alarm) for run in runs for alarm in run["gallery"]["false_alarms"]]
        if not misses and not alarms:
            continue
        lines += [f"### {_name(condition)}", ""]
        if misses:
            counts = Counter(f"{miss['rule_id']}: {miss['mechanism'].split(' (')[0]}" for _, miss in misses)
            lines.append(f"**Missed rings: {len(misses)}** over {len(runs)} seeds.")
            lines += [f"- {count} × {text}" for text, count in sorted(counts.items(), key=lambda item: (-item[1], item[0]))]
            for seed, miss in misses[:EXAMPLES]:
                links = "; ".join(f"{name} ×{info['links']} (strongest {info['strongest']:.2f}"
                                  + (f", explained {'/'.join(info['explained'])}" if info["explained"] else "") + ")"
                                  for name, info in miss["links_among_members"].items()) or "none"
                best = miss["networks"][0] if miss["networks"] else None
                network = (f"best network {best['network_id']} score {best['score']:.3f}, Jaccard {best['jaccard']:.2f}, "
                           f"{'flagged' if best['flagged'] else 'not flagged'}") if best else "in no network"
                lines.append(f"  - Example, seed {seed}, {miss['group_id']} ({miss['rule_id']}, {miss['members']} members): "
                             f"{miss['mechanism']}. Links among members: {links}. {network}.")
            lines.append("")
        if alarms:
            counts = Counter(alarm["rule_id"] for _, alarm in alarms)
            lines.append(f"**False alarms: {len(alarms)}** over {len(runs)} seeds: "
                         + ", ".join(f"{count} × {rule}" for rule, count in sorted(counts.items(), key=lambda item: (-item[1], item[0]))) + ".")
            for seed, alarm in alarms[:EXAMPLES]:
                lines.append(f"  - Example, seed {seed}, {alarm['network_id']} ({alarm['rule_id']}, {alarm['members']} "
                             f"members, score {alarm['score']:.3f}, families {alarm['families']}): {alarm['detector_summary']}")
            lines.append("")

    lines += ["## Limits of this test", "",
              "- The stress scenarios still come from this repository's generator. They change the data in ways the "
              "detector was not designed around, but they are not real claims.",
              "- Predictions were registered in advance, so a hit means the failure was understood, not that it is "
              "acceptable. Misses are reported as they are; ranges were not widened afterwards.",
              "- Each scenario changes one thing at a time. Real data would combine several.", ""]
    return "\n".join(lines)


def write_stress_report(result: dict, command: str, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown(result, command), encoding="utf-8", newline="\n")
